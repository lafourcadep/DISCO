// =============================================================================
// LAMMPS DATA FILE WRITER
//
// Converts the deformed box matrix H' (columns = box vectors) to the LAMMPS
// triclinic standard form via Gram-Schmidt orthogonalisation and writes a
// LAMMPS data file (atomic style).
//
//   lx, ly, lz  : edge lengths of the standard triclinic box
//   xy, xz, yz  : tilt factors
//   Q[3][3]     : rotation from original Cartesian to LAMMPS frame (columns=e1,e2,e3)
//
// Atom positions are projected onto (e1, e2, e3) so that the LAMMPS x-axis
// is aligned with the first box vector.
// =============================================================================
static void writeLAMMPS(
    const string&          filename,
    // deformed box: H'[row][col], columns = box vectors
    const double           Hp[3][3],
    // final atom positions in original Cartesian frame (after Kroupa + U)
    const vector<double>&  posX,
    const vector<double>&  posY,
    const vector<double>&  posZ,
    int                    nbAtoms,
    const string&          element,
    double                 mass)
{
    // ------------------------------------------------------------------
    // 1. Gram-Schmidt: extract LAMMPS box parameters from box vectors
    //    a1 = Hp[:,0],  a2 = Hp[:,1],  a3 = Hp[:,2]
    // ------------------------------------------------------------------
    const double a1[3] = { Hp[0][0], Hp[1][0], Hp[2][0] };
    const double a2[3] = { Hp[0][1], Hp[1][1], Hp[2][1] };
    const double a3[3] = { Hp[0][2], Hp[1][2], Hp[2][2] };

    // e1 = a1 / lx
    const double lx = sqrt(a1[0]*a1[0] + a1[1]*a1[1] + a1[2]*a1[2]);
    const double e1[3] = { a1[0]/lx, a1[1]/lx, a1[2]/lx };

    // xy = a2 · e1 ;  e2 = (a2 - xy*e1) / ly
    const double xy = a2[0]*e1[0] + a2[1]*e1[1] + a2[2]*e1[2];
    double b2[3]    = { a2[0]-xy*e1[0], a2[1]-xy*e1[1], a2[2]-xy*e1[2] };
    const double ly = sqrt(b2[0]*b2[0] + b2[1]*b2[1] + b2[2]*b2[2]);
    const double e2[3] = { b2[0]/ly, b2[1]/ly, b2[2]/ly };

    // xz = a3 · e1 ;  yz = (a3 - xz*e1) · e2 ;  lz from remainder
    const double xz      = a3[0]*e1[0] + a3[1]*e1[1] + a3[2]*e1[2];
    double       b3[3]   = { a3[0]-xz*e1[0], a3[1]-xz*e1[1], a3[2]-xz*e1[2] };
    const double yz      = b3[0]*e2[0] + b3[1]*e2[1] + b3[2]*e2[2];
    double       b3p[3]  = { b3[0]-yz*e2[0], b3[1]-yz*e2[1], b3[2]-yz*e2[2] };
    const double lz      = sqrt(b3p[0]*b3p[0] + b3p[1]*b3p[1] + b3p[2]*b3p[2]);

    // ------------------------------------------------------------------
    // 2. Write file
    // ------------------------------------------------------------------
    ofstream out(filename);
    if (!out) {
        cerr << "ERROR: cannot open LAMMPS output file " << filename << "\n";
        return;
    }

    out << fixed << setprecision(8);

    // Header
    out << "# LAMMPS data file generated by exec_cuda\n\n";
    out << nbAtoms << " atoms\n\n";
    out << "1 atom types\n\n";

    // Box bounds
    out << "0.0 " << lx << " xlo xhi\n";
    out << "0.0 " << ly << " ylo yhi\n";
    out << "0.0 " << lz << " zlo zhi\n";

    // Tilt factors — only written when the box is triclinic
    const double tiltTol = 1e-8;
    if (fabs(xy) > tiltTol || fabs(xz) > tiltTol || fabs(yz) > tiltTol)
        out << xy << " " << xz << " " << yz << " xy xz yz\n";

    // Masses
    out << "\nMasses\n\n";
    out << "1 " << defaultfloat << setprecision(10) << mass << fixed << setprecision(8)
        << "  # " << element << "\n";

    // Atoms
    out << "\nAtoms  # atomic\n\n";

    // e3 = b3p / lz  (computed once here, used for all atoms)
    const double e3[3] = { b3p[0]/lz, b3p[1]/lz, b3p[2]/lz };

    for (int k = 0; k < nbAtoms; k++) {
        // Project position onto LAMMPS frame (e1, e2, e3)
        const double x = posX[k], y = posY[k], z = posZ[k];
        out << k+1 << " 1 "
            << e1[0]*x + e1[1]*y + e1[2]*z << " "
            << e2[0]*x + e2[1]*y + e2[2]*z << " "
            << e3[0]*x + e3[1]*y + e3[2]*z << "\n";
    }

    out.close();
    cout << "Written " << filename << "\n";
}

// =============================================================================
// MAIN
// =============================================================================
int main(int argc, char** argv)
{
    // ---- Arguments: [--cpu] [--fp32] [--gpu-chunk <pairs>] <parameters_file> ----
    bool forceCPU = false;
    GpuOptions gpuOpt;
    const char* paramFile = nullptr;
    bool badArgs = false;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--cpu") == 0) forceCPU = true;
        else if (strcmp(argv[i], "--fp32") == 0) gpuOpt.fp32 = true;
        else if (strcmp(argv[i], "--gpu-chunk") == 0 && i + 1 < argc) {
            char* end = nullptr;
            gpuOpt.chunkPairs = strtod(argv[++i], &end);
            if (*end != '\0' || gpuOpt.chunkPairs < 0.) badArgs = true;
        }
        else if (argv[i][0] == '-' && argv[i][1] == '-') badArgs = true;
        else if (!paramFile) paramFile = argv[i];
        else badArgs = true;
    }
    if (!paramFile || badArgs) {
        cerr << "Usage: " << argv[0] << " [--cpu] [--fp32] [--gpu-chunk <pairs>] <parameters_file>\n"
             << "  --cpu               OpenMP backend even if a GPU is present\n"
             << "  --fp32              GPU only: single-precision pair term (fp64 sums)\n"
             << "  --gpu-chunk <pairs> GPU only: atom-loopon pairs per kernel launch, the host\n"
             << "                      waiting after each (0 = off; default: automatic,\n"
             << "                      on for Apple GPUs through mvcc)\n";
        return 1;
    }

    // ---- Timing: wall-clock time per phase, printed as a summary at the end ----
    using Clock = chrono::steady_clock;
    const Clock::time_point tStart = Clock::now();
    Clock::time_point tPhase = tStart;
    vector<pair<string, double>> timing;           // (phase, seconds)
    auto lap = [&](const string& phase) {
        const Clock::time_point now = Clock::now();
        timing.push_back({phase, chrono::duration<double>(now - tPhase).count()});
        tPhase = now;
    };

    // ---- Backend ----
#ifdef WITH_CUDA
    bool useGPU = !forceCPU;
    if (useGPU && !gpuAvailable()) {
        cerr << "WARNING: no usable CUDA device, falling back to the CPU (OpenMP) backend\n";
        useGPU = false;
    }
#else
    const bool useGPU = false;              // CPU-only build: --cpu is implied
    (void)forceCPU;
#endif
    if (useGPU) {
#ifdef WITH_CUDA
        printGpuInfo();
#endif
    } else {
        cout << "\n--- CPU: " << cpuThreads() << " OpenMP threads (set OMP_NUM_THREADS) ---\n\n";
        if (gpuOpt.fp32 || gpuOpt.chunkPairs >= 0.)
            cerr << "WARNING: --fp32 and --gpu-chunk apply to the GPU backend only; ignored\n";
    }

    // ---- Read parameters ----
    input inputFile(paramFile);
    inputFile.readInputFile();
    lap(useGPU ? "GPU init + read input" : "Read input");

    const double      a0         = inputFile.getA0();
    const vector<int> dim        = inputFile.getNumberOfCells();
    const int         nx=dim[0], ny=dim[1], nz=dim[2];
    const Lattice     lattice    = inputFile.getLattice();
    const string      element    = inputFile.getElement();
    const int         nbLoops    = inputFile.getNumberOfLoops();
    const string      outName    = inputFile.getOutputFileName();
    const string      outFormat  = inputFile.getOutputFormat();
    int               nbAtoms    = inputFile.getNumberOfAtoms();   // changes with prismatic loops
    const double      da         = inputFile.getLooponSize();
    const bool        lineMethod = inputFile.getMethod() == "line";
    const double      segTol     = inputFile.getSegmentTolerance();
#ifdef WITH_CUDA
    if (useGPU && lineMethod && !gpuOpt.fp32 && !gpuLineFp64()) {
        // mvcc build: no fp64 transcendental functions on the GPU
        cerr << "WARNING: this GPU build has no double-precision line kernel (mvcc): Method: line"
                " runs on the CPU; add --fp32 to run it on the GPU\n";
        useGPU = false;
    }
#endif

    const Orientation&   orient = inputFile.getOrientation();
    const vector<double> boxL   = inputFile.getBoxLengths();   // N * a0, or N * period along X/Y/Z
    const double dx = boxL[0], dy = boxL[1], dz = boxL[2];
    vector<Grain> polyGrains;               // polycrystal: grains (seed, orientation, atoms)
    const double dx2 = dx/2., dy2 = dy/2., dz2 = dz/2.;
    const vector<double> compress = {1., 1., 1.};

    const PolycrystalSpec& poly = inputFile.getPolycrystal();
    cout << "\n--- Supercell ---\n";
    if (!poly.active)
        cout << "  " << latticeName(lattice) << ": " << nx << " x " << ny << " x " << nz
             << "  (a0 = " << a0 << " Ang)  |  Atoms: " << nbAtoms << "\n";
    if (orient.active) {
        const char* ax[3] = { "X", "Y", "Z" };
        cout << "  Orientation:";
        for (int a = 0; a < 3; a++)
            cout << " " << ax[a] << " = [" << orient.dir[a][0] << " " << orient.dir[a][1] << " "
                 << orient.dir[a][2] << "] (period " << boxL[a] / dim[a] << " Ang)";
        cout << "\n";
    }
    cout << "  Box: " << dx << " x " << dy << " x " << dz << " Ang\n\n";

    // ---- Generate the lattice ----
    vector<vector<double>> atomPos;
    vector<int> atomGrain;                  // polycrystal: grain of each atom (empty otherwise)
    if (poly.active) {
        const vector<Grain> grains0 = makeGrains(poly);
        PolycrystalResult pc = buildPolycrystal(lattice, a0, poly, grains0);
        nbAtoms = (int)pc.x.size();
        atomPos.resize(nbAtoms);
        for (int a = 0; a < nbAtoms; a++) atomPos[a] = { pc.x[a], pc.y[a], pc.z[a] };
        atomGrain.swap(pc.grain);
        const double V = dx * dy * dz, rho = atomsPerCell(lattice) / (a0 * a0 * a0);
        cout << "  " << latticeName(lattice) << " polycrystal: " << pc.grains.size() << " grains  (a0 = "
             << a0 << " Ang)  |  Atoms: " << nbAtoms << "  (perfect crystal " << lround(rho * V)
             << "; " << pc.removedGB << " removed at GBs, pairs < " << poly.gbMinDistance << " NN)\n"
             << "  Grain   seed (Ang)                         Euler phi1 Phi phi2 (deg)    atoms\n";
        long small = 0;
        for (size_t g = 0; g < pc.grains.size(); g++) {
            double e1, e2, e3;
            eulerFromOrientation(pc.grains[g].o, e1, e2, e3);
            cout << "  " << setw(5) << g + 1 << fixed << setprecision(3)
                 << setw(11) << pc.grains[g].seed[0] << setw(11) << pc.grains[g].seed[1]
                 << setw(11) << pc.grains[g].seed[2] << "   " << setprecision(2)
                 << setw(8) << e1 << setw(8) << e2 << setw(8) << e3 << setw(12) << pc.grains[g].atoms
                 << defaultfloat << setprecision(6) << "\n";
            if (pc.grains[g].atoms < 200) small++;
        }
        if (small)
            cerr << "WARNING: " << small << " grain(s) hold fewer than 200 atoms\n";
        polyGrains = pc.grains;
    } else if (orient.active) {
        const double L[3] = { dx, dy, dz };
        atomPos = generateOrientedLattice(lattice, orient, L, a0);
        if ((int)atomPos.size() != nbAtoms) {
            cerr << "ERROR: oriented lattice has " << atomPos.size() << " atoms, expected " << nbAtoms
                 << " (box not commensurate with the lattice)\n";
            abort();
        }
    } else
        atomPos = generateLattice(lattice, nx, ny, nz, a0);
    lap(poly.active ? string("Polycrystal (CPU)") : string(latticeName(lattice)) + " lattice (CPU)");

    // ---- Build dislocation loops (host — only to generate loopon positions) ----
    vector<loop> listLoop;
    listLoop.reserve(nbLoops);
    vector<double> planeSpacing(nbLoops);   // atomic-plane spacing of each loop normal
    vector<BurgersClass> burgersClass(nbLoops);   // perfect / Frank / Shockley / other
    for (int i = 0; i < nbLoops; i++) {
        double d;
        // m, n, Side, Dir_1/2, Vertex_dir, Vertices: crystal frame; Center: lab frame
        const double boxOrigin[3] = { -dx2, -dy2, -dz2 };   // a lattice site (box corner)
        const vector<double> c = orient.active
            ? snapToMidPlaneOriented(inputFile.getCenter(i), inputFile.getN(i), orient, boxOrigin,
                                     a0, d, lattice)
            : snapToMidPlane(inputFile.getCenter(i), inputFile.getN(i), a0, nx, ny, nz, d, lattice);
        const vector<double> mL = rotateToLab(orient, inputFile.getM(i));
        const vector<double> nL = rotateToLab(orient, inputFile.getN(i));
        vector<double> sideL = rotateToLab(orient, inputFile.getSide(i));
        if (orient.active && sideL.empty())   // crystal-frame default axis, rotated
            sideL = rotateToLab(orient, defaultInPlaneAxis(inputFile.getM(i), inputFile.getN(i)));
        const string shape = inputFile.getShape(i);
        burgersClass[i] = classifyBurgers(lattice, inputFile.getM(i), inputFile.getN(i));
        {
            const vector<double> m = inputFile.getM(i);
            switch (burgersClass[i]) {
            case BurgersClass::PERFECT: break;
            case BurgersClass::FRANK:
                cout << "  Loop " << i+1 << ": Frank loop, b = a0/3<111> normal to its {111} plane:"
                     << " stacking fault inside the contour (intrinsic if vacancy, extrinsic if"
                     << " interstitial)\n";
                break;
            case BurgersClass::SHOCKLEY:
                if (shockleyFaultIsStable(m, inputFile.getN(i)))
                    cout << "  Loop " << i+1 << ": Shockley partial loop, b = a0/6<112> in its {111}"
                         << " plane: intrinsic stacking fault inside the contour\n";
                else
                    cerr << "WARNING: loop " << i+1 << ": Shockley b = a0/2 [" << m[0] << " " << m[1]
                         << " " << m[2] << "] has the wrong sense for n: the cut stacks the layer above"
                         << " it straight over the layer below (AA), not an intrinsic fault; reverse m"
                         << " (or n) for a stable Shockley loop\n";
                break;
            default:
                cerr << "WARNING: loop " << i+1 << ": b = a0/2 [" << m[0] << " " << m[1] << " " << m[2]
                     << "] is not a translation of the " << latticeName(lattice) << " lattice"
                     << (lattice == Lattice::FCC
                         ? " (perfect FCC: m = <110>; faulted: Frank 2/3<111> on {111}, Shockley 1/3<112> in {111})"
                         : " (perfect BCC: m = <111>)")
                     << ": the cut surface leaves a fault\n";
            }
        }
        const bool isPolygon = (shape == "polygon" || shape == "hexagonal");
        vector< vector<double> > verts;
        if (isPolygon) {
            if (inputFile.getSides(i) > 0)
                verts = regularPolygon(inputFile.getSides(i), inputFile.getRadius(i), sideL, mL, nL);
            else
                for (const vector<double>& v : inputFile.getVertices(i)) verts.push_back(rotateToLab(orient, v));
        }
        loop l = isPolygon
            ? loop(da, verts, inputFile.getCornerRadius(i), c, mL, nL, a0, compress, sideL)
            : (shape == "rectangular")
            ? loop(da, inputFile.getHalfM(i), inputFile.getHalfP(i), inputFile.getCornerRadius(i),
                   c, mL, nL, a0, compress, sideL)
            : (shape == "parallelogram")
            ? loop(da, inputFile.getHalfM(i), inputFile.getHalfP(i),
                   rotateToLab(orient, inputFile.getDir1(i)), rotateToLab(orient, inputFile.getDir2(i)),
                   c, mL, nL, a0, compress)
            : loop(da, inputFile.getRadius(i), c, mL, nL, a0, compress);
        l.generateSurface();
        if (!lineMethod) l.generateLoopons();
        const int nSeg = lineMethod ? (int)l.polyline(segTol).size() : 0;
        const vector<double>& c0 = inputFile.getCenter(i);
        const double shift = sqrt((c[0]-c0[0])*(c[0]-c0[0]) + (c[1]-c0[1])*(c[1]-c0[1])
                                  + (c[2]-c0[2])*(c[2]-c0[2]));
        const double b = l.getBurgers()[0];
        planeSpacing[i] = d;
        cout << "  Loop " << i+1 << ": " << inputFile.getShape(i)
             << " | " << (lineMethod ? nSeg : l.getNumberOfLoopons())
             << (lineMethod ? " segments | " : " loopons | ")
             << matterName(matterType(l)) << "\n";
        if (shape == "rectangular") {
            cout << "    size   : Half_m " << inputFile.getHalfM(i) / b << " |b|, Half_p "
                 << inputFile.getHalfP(i) / b << " |b|  (|b| = " << b << " Ang)\n";
            if (!inputFile.getSide(i).empty()) {
                const vector<double> sd = inputFile.getSide(i);
                cout << "    side   : Half_m along [" << sd[0] << " " << sd[1] << " " << sd[2]
                     << "], Half_p along Side x n\n";
            }
        }
        else if (isPolygon) {
            if (inputFile.getSides(i) > 0)
                cout << "    size   : " << inputFile.getSides(i) << " sides, circumradius "
                     << inputFile.getRadius(i) / b << " |b|  (|b| = " << b << " Ang)\n";
            else
                cout << "    size   : " << l.getNumberOfVertices() << " vertices  (|b| = "
                     << b << " Ang)\n";
            cout << "    contour: area " << l.getContourArea() << " Ang^2";
            if (!lineMethod) cout << " (loopons " << l.getNumberOfLoopons() * l.getSurface() << ")";
            cout << ", corner radius " << l.getCornerRadius() << " Ang\n";
        }
        else if (shape == "parallelogram")
            cout << "    size   : Half_1 " << inputFile.getHalfM(i) / b << " |b|, Half_2 "
                 << inputFile.getHalfP(i) / b << " |b|  (|b| = " << b << " Ang)\n";
        else
            cout << "    size   : Radius " << inputFile.getRadius(i) / b
                 << " |b|  (|b| = " << b << " Ang)\n";
        cout << "    centre : " << c[0] << " " << c[1] << " " << c[2]
             << " Ang  (moved " << shift << " Ang along n to the mid-plane,"
             << " plane spacing " << d << " Ang)\n";
        listLoop.push_back(l);
    }
    lap("Loops + loopons (CPU)");


    // ---- Flatten atom positions into SoA host vectors ----
    // SoA layout: coalesced GPU reads, contiguous CPU reads
    vector<double> hAtomX(nbAtoms), hAtomY(nbAtoms), hAtomZ(nbAtoms);
    for (int i = 0; i < nbAtoms; i++) {
        hAtomX[i] = atomPos[i][0];
        hAtomY[i] = atomPos[i][1];
        hAtomZ[i] = atomPos[i][2];
    }
    vector<vector<double>>().swap(atomPos);

    // ---- Loops with b.n != 0: remove (vacancy) or duplicate (interstitial) the slab ----
    //   Slabs are all selected on the perfect lattice. Vacancy slabs are deleted now,
    //   before the displacement sum; interstitial copies are appended after it, at
    //   their original site with displacement u(x) + side * b (see prismatic.hpp).
    struct Copy { int atom; double shift[3]; };
    vector<Copy> copies;
    {
        vector<char> removed(nbAtoms, 0);
        double dVolume = 0.;
        bool any = false;
        for (int l = 0; l < nbLoops; l++) {
            if (matterType(listLoop[l]) == MatterType::NONE) continue;
            if (inputFile.getMatter(l) == "none") {
                cout << "  Loop " << l+1 << ": b.n != 0 but Matter: none -> displacement only\n";
                continue;
            }
            if (!any) { cout << "\n--- Prismatic loops: atoms added / removed ---\n"; any = true; }
            const SlabResult sl = prismaticSlab(listLoop[l], planeSpacing[l],
                                                hAtomX, hAtomY, hAtomZ, dx, dy, dz);
            const int    ns    = (int)sl.atoms.size();
            const double area  = lineMethod ? listLoop[l].getContourArea()
                                            : listLoop[l].getNumberOfLoopons() * listLoop[l].getSurface();
            const double nomin = nbAtoms / (dx * dy * dz) * area * sl.height;
            // Interstitial: the kept atoms nearest the cut sit d/2 from the loopon plane,
            // and the discrete loopon sum is only smooth there for a step <~ 0.7 * d/2
            if (!lineMethod && sl.type == MatterType::INTERSTITIAL && da > 0.35 * sl.spacing)
                cerr << "WARNING: loop " << l+1 << " is interstitial and Loopon_size = " << da
                     << " Ang > 0.35 d = " << 0.35 * sl.spacing << " Ang: the planes next to the"
                     << " cut will be noisy; use Loopon_size <= " << 0.35 * sl.spacing << "\n";
            if (sl.type == MatterType::VACANCY) {
                for (int a : sl.atoms) removed[a] = 1;
                dVolume -= area * sl.height;
            } else {
                // Copy shift for each side of the cut: side * b, plus for a Frank loop the
                // Shockley shift that stacks the inserted layer as an extrinsic fault
                double shift[2][3];
                for (int sd = 0; sd < 2; sd++) {
                    const double sign = sd == 0 ? 1. : -1.;
                    const double v[3] = { sign*sl.b[0], sign*sl.b[1], sign*sl.b[2] };
                    if (burgersClass[l] == BurgersClass::FRANK) {
                        // crystal frame (lattice translations), then back to the lab
                        const vector<double> nh = rotateToCrystal(orient, listLoop[l].getN());
                        const vector<double> vc = rotateToCrystal(orient, { v[0], v[1], v[2] });
                        const double nhat[3] = { nh[0], nh[1], nh[2] }, vcr[3] = { vc[0], vc[1], vc[2] };
                        double out[3];
                        frankCopyShift(vcr, nhat, a0, out);
                        const vector<double> ol = rotateToLab(orient, { out[0], out[1], out[2] });
                        for (int c = 0; c < 3; c++) shift[sd][c] = ol[c];
                    } else
                        for (int c = 0; c < 3; c++) shift[sd][c] = v[c];
                }
                for (int k = 0; k < ns; k++) {
                    const double* sh = shift[sl.side[k] > 0 ? 0 : 1];
                    copies.push_back({ sl.atoms[k], { sh[0], sh[1], sh[2] } });
                }
                dVolume += area * sl.height;
            }
            cout << "  Loop " << l+1 << ": " << matterName(sl.type) << ", |b.n| = " << sl.height
                 << " Ang = " << sl.planes << " plane(s) of d = " << sl.spacing << " Ang, "
                 << (sl.type == MatterType::VACANCY ? "removed " : "added ") << ns
                 << " atoms (rho A |b.n| = " << setprecision(1) << fixed << nomin << ")\n"
                 << defaultfloat << setprecision(6);
        }
        if (any) {
            // Drop removed atoms; renumber the copy sources (a copy of a removed atom is dropped)
            vector<int> newIndex(nbAtoms, -1);
            int k = 0;
            for (int a = 0; a < nbAtoms; a++) {
                if (removed[a]) continue;
                newIndex[a] = k;
                hAtomX[k] = hAtomX[a];  hAtomY[k] = hAtomY[a];  hAtomZ[k] = hAtomZ[a];
                if (!atomGrain.empty()) atomGrain[k] = atomGrain[a];
                k++;
            }
            hAtomX.resize(k);  hAtomY.resize(k);  hAtomZ.resize(k);
            if (!atomGrain.empty()) atomGrain.resize(k);
            vector<Copy> kept;
            for (Copy c : copies)
                if (newIndex[c.atom] >= 0) { c.atom = newIndex[c.atom]; kept.push_back(c); }
            copies.swap(kept);
            cout << "  Atoms: " << nbAtoms << " -> " << k + (int)copies.size()
                 << "  (" << nbAtoms - k << " removed, " << copies.size() << " added)\n"
                 << "  Box not deformed: expected volume change " << dVolume << " Ang^3 ("
                 << 100. * dVolume / (dx * dy * dz) << " %), relax it with NPT / box/relax\n\n";
            nbAtoms = k;
        }
    }
    lap("Prismatic slabs (CPU)");

    // ---- Loopon positions (SoA) and loop physics for the backend ----
    //   b = getBurgers() (|b| per component), m, n normalised, dS = getSurface()
    vector<LoopData> loopData(nbLoops);
    for (int l = 0; l < nbLoops; l++) {
        const loop& lp = listLoop[l];
        const int nLp = lp.getNumberOfLoopons();
        LoopData& d = loopData[l];
        d.x.resize(nLp); d.y.resize(nLp); d.z.resize(nLp);
        for (int p = 0; p < nLp; p++) {
            auto pos = lp.getOneLoopon(p);
            d.x[p] = pos[0];  d.y[p] = pos[1];  d.z[p] = pos[2];
        }
        const vector<double> b = lp.getBurgers(), m = lp.getM(), n = lp.getN();
        d.phys = { b[0], b[1], b[2], m[0], m[1], m[2], n[0], n[1], n[2], lp.getSurface() };
        if (lineMethod) {
            d.line = true;
            for (const auto& v : lp.polyline(segTol)) {
                d.vx.push_back(v[0]); d.vy.push_back(v[1]); d.vz.push_back(v[2]);
            }
            const vector<double> c = lp.getCenter();
            d.cx = c[0]; d.cy = c[1]; d.cz = c[2];
        }
    }

    // ---- Kroupa displacement sum ----
    vector<double> hDisplX(nbAtoms, 0.), hDisplY(nbAtoms, 0.), hDisplZ(nbAtoms, 0.);
    const AtomArrays atoms = { hAtomX.data(), hAtomY.data(), hAtomZ.data(),
                               hDisplX.data(), hDisplY.data(), hDisplZ.data(), nbAtoms };
    BackendTiming bt;
    if (nbLoops == 0) {
        cout << "No dislocation loop: atoms keep their lattice positions\n";
    } else if (useGPU) {
#ifdef WITH_CUDA
        kroupaGPU(atoms, loopData, dx, dy, dz, gpuOpt, bt);
        timing.push_back({"Alloc + upload atoms (CPU->GPU)", bt.upload});
        timing.push_back({gpuOpt.fp32 ? "Kroupa kernels (GPU, fp32)" : "Kroupa kernels (GPU)", bt.kernels});
        timing.push_back({"Download displacements (GPU->CPU)", bt.download});
#endif
    } else {
        kroupaCPU(atoms, loopData, dx, dy, dz, bt);
        timing.push_back({"Kroupa kernels (CPU)", bt.kernels});
    }
    tPhase = Clock::now();

    // ---- Interstitial copies: same site, displacement u(x) + side * b ----
    for (const Copy& c : copies) {
        hAtomX.push_back(hAtomX[c.atom]);
        hAtomY.push_back(hAtomY[c.atom]);
        hAtomZ.push_back(hAtomZ[c.atom]);
        if (!atomGrain.empty()) atomGrain.push_back(atomGrain[c.atom]);
        hDisplX.push_back(hDisplX[c.atom] + c.shift[0]);
        hDisplY.push_back(hDisplY[c.atom] + c.shift[1]);
        hDisplZ.push_back(hDisplZ[c.atom] + c.shift[2]);
    }
    nbAtoms += (int)copies.size();

    // ---- Build loop descriptors for box deformation ----
    //
    //   getBurgers()[j] = |b|  (same for all j when compress={1,1,1})
    //   getM()[j]       = normalised Burgers direction
    //   => actual Burgers component  b_actual[j] = getBurgers()[j] * getM()[j]
    //   Total swept area A = nLoopons * dS
    //
    vector<LoopDesc> loopDescs;
    loopDescs.reserve(nbLoops);
    for (int l = 0; l < nbLoops; l++) {
        const loop& lp = listLoop[l];
        LoopDesc d;
        auto bvec = lp.getBurgers();   // (|b|, |b|, |b|)
        auto mvec = lp.getM();         // normalised direction
        auto nvec = lp.getN();
        for (int j = 0; j < 3; j++) {
            d.b[j] = bvec[j] * mvec[j];   // b_actual[j] = |b| * m_j
            d.n[j] = nvec[j];
        }
        d.A = lineMethod ? lp.getContourArea()
                         : static_cast<double>(lp.getNumberOfLoopons()) * lp.getSurface();
        loopDescs.push_back(d);
    }

    // ---- Compute the pure stretch tensor U (polar decomposition of F=I+β) ----
    const double V_box = dx * dy * dz;
    //    const Mat3 U = computeU(loopDescs, V_box);
    Mat3 U = {};
    for (int i=0;i<3;i++) {
      for (int j=0;j<3;j++) {
        U[i][j] = 0.;
      }
    }
    U[0][0]=1.0;
    U[1][1]=1.0;
    U[2][2]=1.0;    
    // Deformed box vectors: H'[:,j] = U * H[:,j]  (H = diag(dx,dy,dz))
    //   H'[i][j] = U[i][j] * {dx, dy, dz}[j]
    const double Hprime[3][3] = {
        { U[0][0]*dx, U[0][1]*dy, U[0][2]*dz },
        { U[1][0]*dx, U[1][1]*dy, U[1][2]*dz },
        { U[2][0]*dx, U[2][1]*dy, U[2][2]*dz }
    };

    cout << "Box deformation (U - I):\n" << fixed << setprecision(8);
    for (int i = 0; i < 3; i++) {
        cout << "  [ ";
        for (int j = 0; j < 3; j++)
            cout << U[i][j] - (i==j ? 1.0 : 0.0) << " ";
        cout << "]\n";
    }

    // ---- Compute final atom positions (Kroupa + PBC wrap + box deformation) ----
    // Stored once and reused by the XYZ and/or LAMMPS writers below.
    vector<double> finalX(nbAtoms), finalY(nbAtoms), finalZ(nbAtoms);
    for (int k = 0; k < nbAtoms; k++) {
        // 1. Add Kroupa displacement (original centred frame)
        double rx = hAtomX[k] + hDisplX[k];
        double ry = hAtomY[k] + hDisplY[k];
        double rz = hAtomZ[k] + hDisplZ[k];

        // 2. Wrap in the ORIGINAL box (fractional coords are preserved by U)
        if      (rx >  dx2) rx -= dx;  else if (rx < -dx2) rx += dx;
        if      (ry >  dy2) ry -= dy;  else if (ry < -dy2) ry += dy;
        if      (rz >  dz2) rz -= dz;  else if (rz < -dz2) rz += dz;

        // 3. Shift to [0, d] then apply U  →  positions in the deformed-box frame
        //    r_out = U · (r_wrapped + (dx2,dy2,dz2))
        double ox = rx + dx2, oy = ry + dy2, oz = rz + dz2;
        finalX[k] = U[0][0]*ox + U[0][1]*oy + U[0][2]*oz;
        finalY[k] = U[1][0]*ox + U[1][1]*oy + U[1][2]*oz;
        finalZ[k] = U[2][0]*ox + U[2][1]*oy + U[2][2]*oz;
    }
    lap("Final positions (CPU)");

    // ---- Write XYZ (extended XYZ format) ----
    if (outFormat == "xyz" || outFormat == "both") {
        ofstream out(outName);
        if (!out) {
            cerr << "ERROR: cannot open output file " << outName << "\n";
            return 1;
        }
        cout << "Writing " << outName << " ...\n";
        out << nbAtoms << "\n";
        // Lattice string: box vectors a1, a2, a3 listed as rows
        // a_k = H'[:,k] = (Hprime[0][k], Hprime[1][k], Hprime[2][k])
        out << "Lattice=\""
            << Hprime[0][0] << " " << Hprime[1][0] << " " << Hprime[2][0] << "  "
            << Hprime[0][1] << " " << Hprime[1][1] << " " << Hprime[2][1] << "  "
            << Hprime[0][2] << " " << Hprime[1][2] << " " << Hprime[2][2]
            << "\" Properties=species:S:1:pos:R:3" << (atomGrain.empty() ? "" : ":grain:I:1") << "\n";
        out << fixed << setprecision(8);
        for (int k = 0; k < nbAtoms; k++) {
            out << element << " " << finalX[k] << " " << finalY[k] << " " << finalZ[k];
            if (!atomGrain.empty()) out << " " << atomGrain[k] + 1;
            out << "\n";
        }
        out.close();
        cout << "Written " << outName << "\n";
    }

    // ---- Write LAMMPS data file ----
    if (outFormat == "lammps" || outFormat == "both") {
        string lmpName = outName.substr(0, outName.size()-3) + "lmp";
        writeLAMMPS(lmpName, Hprime, finalX, finalY, finalZ, nbAtoms, element, inputFile.getMass());
    }

    // ---- Polycrystal: grain table (1-based ids, as in the xyz 'grain' column) ----
    if (poly.active && outFormat != "none") {
        const string gName = outName.substr(0, outName.size()-4) + "_grains.txt";
        ofstream gout(gName);
        gout << "# DISCO polycrystal: " << polyGrains.size() << " grains, box " << dx << " " << dy << " "
             << dz << " Ang (origin at the box centre; xyz/lmp files are shifted by +L/2)\n"
             << "# R: rows = crystal directions of the lab x, y, z axes (lab = R crystal); Euler: Bunge, deg\n"
             << "# grain  seed_x seed_y seed_z  phi1 Phi phi2  R00 R01 R02 R10 R11 R12 R20 R21 R22  atoms\n";
        gout << setprecision(10);
        for (size_t g = 0; g < polyGrains.size(); g++) {
            double e1, e2, e3;
            eulerFromOrientation(polyGrains[g].o, e1, e2, e3);
            long na = 0;
            for (int a = 0; a < nbAtoms; a++) na += (atomGrain[a] == (int)g);
            gout << g + 1 << "  " << polyGrains[g].seed[0] << " " << polyGrains[g].seed[1] << " "
                 << polyGrains[g].seed[2] << "  " << e1 << " " << e2 << " " << e3 << " ";
            for (int i = 0; i < 3; i++)
                for (int j = 0; j < 3; j++) gout << " " << polyGrains[g].o.R[i][j];
            gout << "  " << na << "\n";
        }
        cout << "Written " << gName << "\n";
    }

    if (outFormat != "xyz" && outFormat != "lammps" && outFormat != "both" && outFormat != "none")
        cerr << "WARNING: unknown Output_format \"" << outFormat
             << "\". Nothing written. Use xyz, lammps, both or none.\n";

    lap("Write output (CPU)");

    // ---- Timing summary ----
    const double total = chrono::duration<double>(Clock::now() - tStart).count();
    cout << "\n--- Timing summary ---\n" << fixed << setprecision(3);
    for (const auto& ph : timing)
        cout << "  " << left << setw(36) << ph.first << right << setw(10) << ph.second << " s  "
             << setw(6) << setprecision(1) << 100. * ph.second / total << " %\n" << setprecision(3);
    cout << "  " << left << setw(36) << "Total (wall clock)" << right << setw(10) << total << " s\n";

    // Per-loop cost; a pair is one atom x one loopon (the kernel sums its periodic images)
    const string dev = useGPU ? "GPU" : "CPU";
    const bool perLoop = nbLoops <= 20;   // ponytail: long lists only summarised
    cout << "\n  " << dev << (perLoop ? (useGPU ? " per loop (loopon upload + kernel):" : " per loop:") : ":") << "\n";
    double pairsTotal = 0., kernelSec = 0.;
    for (int l = 0; l < nbLoops; l++) {
        const int    nLp   = lineMethod ? (int)listLoop[l].polyline(segTol).size()
                                        : listLoop[l].getNumberOfLoopons();
        const double pairs = double(nbAtoms) * nLp;
        pairsTotal += pairs;
        kernelSec  += bt.loopSec[l];
        if (perLoop)
            cout << "    Loop " << setw(3) << l+1 << " : " << setw(7) << nLp
                 << (lineMethod ? " segments " : " loopons  ")
                 << setw(10) << bt.loopSec[l] << " s  " << setw(8) << setprecision(1)
                 << pairs / bt.loopSec[l] / 1e6 << " M pairs/s\n" << setprecision(3);
    }
    cout << "    All loops: " << setprecision(3) << scientific << pairsTotal << fixed
         << (lineMethod ? " atom-segment pairs in " : " atom-loopon pairs in ")
         << kernelSec << " s  ->  " << setprecision(1)
         << pairsTotal / kernelSec / 1e6 << " M pairs/s\n";

    cout << "Done.\n";
    return 0;
}
